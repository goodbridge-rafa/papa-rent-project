export function deviceLocale(): AppLocale {
  // Also runs during web pre-rendering, in Node, where there is no `navigator` and the module may
  // throw. Without a known language the fallback applies, never an exception mid-startup.
  try {
    const code = getLocales()[0]?.languageCode ?? "en";
    return code === "nl" ? "nl" : "en";
  } catch {
    return "en";
  }
}

export function initI18n(locale: AppLocale = deviceLocale()) {
  if (i18n.isInitialized) {
    void i18n.changeLanguage(locale);
    return i18n;
  }
  void i18n.use(initReactI18next).init({
    resources: { nl: { translation: nl }, en: { translation: en } },
    lng: locale,
    fallbackLng: "en",
    interpolation: { escapeValue: false },
  });
  return i18n;
}

